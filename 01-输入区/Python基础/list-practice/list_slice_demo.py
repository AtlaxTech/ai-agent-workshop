s = ["A", "C", "E", "B", "D", "E", "G"]

slice1 = s[0:5:1]
slice2 = s[0:5:2]
slice3 = s[0:-2:1]

# 切片1 s[0:5:1] 为: ['A', 'C', 'E', 'B', 'D']
print(f"切片1 s[0:5:1] 为: {slice1}")
# 切片2 s[0:5:2] 为: ['A', 'E', 'D']
print(f"切片2 s[0:5:2] 为: {slice2}")
# 切片3 s[0:-2:1] 含义：从索引为 0 的位置开始切，截取到反向索引为 -2 的位置，每 1 个切一次（步长）
# 结果为: ['A', 'C', 'E', 'B', 'D']
print(f"切片3 s[0:-2:1] 为: {slice3}")
